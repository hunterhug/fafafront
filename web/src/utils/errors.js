// 按错误码取本地化文案，未命中时回退后端原始 msg
export function errorMessage(id, fallbackMsg) {
  if (id == null) return fallbackMsg || t('common.failed')
  // 激活码(100024)/重置码(100029)错误：透出后端剩余次数或"已作废"提示
  if ((id === 100024 || id === 100029) && fallbackMsg) {
    if (fallbackMsg.includes('invalidated')) return t('err.codeInvalidated')
    const m = fallbackMsg.match(/(\d+)\s*attempts?\s*left/)
    if (m) return t('err.codeWrongRemain', { n: m[1] })
  }
  if (ERR_MAP[id]) return t(ERR_MAP[id])
  return fallbackMsg || t('common.failed')
}
